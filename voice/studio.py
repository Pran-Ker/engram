if __name__ == "__main__":
    # `python studio.py url|status` talks to the deployed app without starting an ephemeral one.
    import sys

    action = sys.argv[1] if len(sys.argv) > 1 else "url"
    if action == "url":
        print(modal.Function.from_name(APP, "web").get_web_url())
    elif action == "status":
        print(modal.Function.from_name(APP, "check").remote())
    else:
        raise SystemExit("usage: python studio.py url|status")
